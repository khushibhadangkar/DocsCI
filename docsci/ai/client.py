"""Gemini API client and offline mock client for DocsCI."""

from __future__ import annotations

import json
import logging
import os
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Protocol

from docsci.models import CommitEntry

logger = logging.getLogger(__name__)

DEFAULT_GEMINI_MODEL = "gemini-2.5-flash"
GEMINI_API_BASE = "https://generativelanguage.googleapis.com/v1beta/models"


class LLMClientProtocol(Protocol):
    """Protocol for LLM summarization clients."""

    def generate_summary(
        self,
        commits: list[CommitEntry],
        prompt_template: str,
    ) -> str:
        """Generate release summary from structured commit list."""
        ...


class GeminiClient:
    """Client for Google Gemini API using pure standard library HTTP."""

    def __init__(
        self,
        api_key: str | None = None,
        model: str = DEFAULT_GEMINI_MODEL,
        timeout: float = 30.0,
    ) -> None:
        self.api_key = api_key or os.getenv("GEMINI_API_KEY")
        self.model = model
        self.timeout = timeout

    def generate_summary(
        self,
        commits: list[CommitEntry],
        prompt_template: str,
    ) -> str:
        """Call Gemini API with structured commit entries and return summary text."""
        if not self.api_key:
            raise ValueError(
                "GEMINI_API_KEY environment variable is not set. "
                "Provide a key or use the offline mock client."
            )

        # Build clean, privacy-safe commit representation (no repo paths, no customer data)
        structured_commits: list[str] = []
        for c in commits:
            scope_str = f"({c.scope})" if c.scope else ""
            breaking_str = " [BREAKING]" if c.breaking else ""
            structured_commits.append(
                f"- [{c.short_hash}] {c.type}{scope_str}{breaking_str}: {c.description}"
            )

        commit_text = "\n".join(structured_commits)
        full_prompt = prompt_template.replace("{commits_list}", commit_text)

        url = f"{GEMINI_API_BASE}/{self.model}:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {
                    "parts": [{"text": full_prompt}],
                }
            ],
            "generationConfig": {
                "temperature": 0.2,
                "topP": 0.8,
                "maxOutputTokens": 1024,
            },
        }

        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data_bytes,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                resp_data = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as he:
            err_body = he.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"Gemini API returned HTTP {he.code}: {err_body}") from he
        except Exception as exc:
            raise RuntimeError(f"Gemini API request failed: {exc}") from exc

        candidates = resp_data.get("candidates", [])
        if not candidates:
            return "No content generated by the model."

        parts = candidates[0].get("content", {}).get("parts", [])
        if not parts:
            return "No text returned by the model."

        return str(parts[0].get("text", "")).strip()


class MockLLMClient:
    """Offline mock client simulating Gemini responses for reliable testing."""

    def __init__(
        self,
        custom_response: str | None = None,
        inject_hallucination: bool = False,
    ) -> None:
        self.custom_response = custom_response
        self.inject_hallucination = inject_hallucination

    def generate_summary(
        self,
        commits: list[CommitEntry],
        prompt_template: str,
    ) -> str:
        """Produce deterministic, structured summary based on input commits."""
        if self.custom_response:
            return self.custom_response

        if not commits:
            return "This maintenance release includes routine stability updates and optimizations."

        highlights: list[str] = []
        updates: list[str] = []

        for c in commits:
            if c.breaking:
                highlights.append(f"Breaking change: {c.description.rstrip('.')}.")
            elif c.type == "feat":
                updates.append(f"Added capability: {c.description.rstrip('.')}.")
            elif c.type == "fix":
                updates.append(f"Resolved issue: {c.description.rstrip('.')}.")
            elif c.type in ("perf", "refactor"):
                updates.append(f"Performance update: {c.description.rstrip('.')}.")
            elif c.type == "docs":
                updates.append(f"Documentation update: {c.description.rstrip('.')}.")

        lines: list[str] = []
        if highlights:
            lines.append("### Key highlights")
            for h in highlights:
                lines.append(f"- {h}")
            lines.append("")

        lines.append("### Notable updates")
        for u in updates:
            lines.append(f"- {u}")

        if self.inject_hallucination:
            # Inject an invented claim that has no corroborating commit
            lines.append(
                "- Added autonomous AI quantum data recovery with zero-latency cross-region replication."
            )

        return "\n".join(lines)


def get_llm_client(force_mock: bool = False) -> LLMClientProtocol:
    """Return appropriate LLM client based on environment and flags."""
    api_key = os.getenv("GEMINI_API_KEY")
    if force_mock or not api_key:
        return MockLLMClient()
    return GeminiClient(api_key=api_key)


def load_prompt_template(prompt_path: Path | str) -> tuple[str, str]:
    """Load prompt template and extract version comment from header."""
    path = Path(prompt_path)
    if not path.is_file():
        # Fallback default
        return (
            "Summarize the following release changes in plain language:\n{commits_list}",
            "default-v1",
        )

    content = path.read_text(encoding="utf-8")
    version = "v1"
    for line in content.splitlines()[:5]:
        if "Prompt Version:" in line:
            parts = line.split("Prompt Version:", 1)
            version = parts[1].replace("-->", "").strip()
            break

    return content, version
